#!/usr/bin/env node
/**
 * MillLedger Remediation Tracker Validator (check-tracker.mjs)
 *
 * Enforces the strict status state machine and integrity invariants:
 * 1. Valid states and transitions (no skipped states).
 * 2. VERIFIED criteria: regression test, fixCommit, verifyEvidence (>= 2), siblingSweep done, distinct verifier.
 * 3. Topological order: dependsOn items must be VERIFIED before dependent starts IN-PROGRESS.
 * 4. P0/P1 WONT-FIX requires owner approval note.
 * 5. Unique IDs across all work items.
 * 6. tracker.md view is exactly synchronized with tracker.json.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT = join(__dirname, '../..');
const TRACKER_JSON_PATH = join(__dirname, 'tracker.json');
const TRACKER_MD_PATH = join(__dirname, 'tracker.md');

const VALID_STATUSES = new Set([
  'OPEN',
  'IN-PROGRESS',
  'FIXED-UNVERIFIED',
  'VERIFIED',
  'REJECTED',
  'REOPENED',
  'BLOCKED',
  'WONT-FIX',
]);

const VALID_SEVERITIES = new Set(['P0', 'P1', 'P2', 'P3']);
const VALID_EFFORTS = new Set(['S', 'M', 'L']);
const VALID_APPROVALS = new Set(['schema', 'permission', 'API', 'none']);

const ALLOWED_TRANSITIONS = {
  OPEN: new Set(['IN-PROGRESS', 'BLOCKED', 'WONT-FIX']),
  'IN-PROGRESS': new Set(['FIXED-UNVERIFIED', 'BLOCKED']),
  'FIXED-UNVERIFIED': new Set(['VERIFIED', 'REJECTED']),
  REJECTED: new Set(['IN-PROGRESS']),
  VERIFIED: new Set(['REOPENED']),
  REOPENED: new Set(['IN-PROGRESS']),
  BLOCKED: new Set(['OPEN', 'IN-PROGRESS']),
  'WONT-FIX': new Set(['OPEN']),
};

export function generateMarkdown(items) {
  const findings = items.filter((i) => !i.id.startsWith('CLUSTER-'));
  const clusters = items.filter((i) => i.id.startsWith('CLUSTER-'));

  const statusCounts = {};
  const severityCounts = { P0: 0, P1: 0, P2: 0, P3: 0 };
  const tierCounts = {};

  for (const item of findings) {
    statusCounts[item.status] = (statusCounts[item.status] ?? 0) + 1;
    severityCounts[item.severity] = (severityCounts[item.severity] ?? 0) + 1;
    tierCounts[item.tier] = (tierCounts[item.tier] ?? 0) + 1;
  }

  const verifiedCount = statusCounts['VERIFIED'] ?? 0;
  const wontFixCount = statusCounts['WONT-FIX'] ?? 0;
  const totalFindings = findings.length;
  const progressPercent = totalFindings > 0 ? (((verifiedCount + wontFixCount) / totalFindings) * 100).toFixed(1) : '0.0';

  let md = `# MillLedger Remediation Work Tracker

> **Source of Truth**: \`audit/tracker/tracker.json\`  
> **Notice**: Do not edit this file manually. It is strictly generated by \`check-tracker.mjs\`.  
> **Last Updated**: 2026-11-20  
> **Progress**: ${verifiedCount + wontFixCount} / ${totalFindings} closed (${progressPercent}%)

---

## 1. Executive Status Summary

### By Status
| Status | Count | Percentage |
|---|---|---|
| OPEN | ${statusCounts['OPEN'] ?? 0} | ${(((statusCounts['OPEN'] ?? 0) / totalFindings) * 100).toFixed(1)}% |
| IN-PROGRESS | ${statusCounts['IN-PROGRESS'] ?? 0} | ${(((statusCounts['IN-PROGRESS'] ?? 0) / totalFindings) * 100).toFixed(1)}% |
| FIXED-UNVERIFIED | ${statusCounts['FIXED-UNVERIFIED'] ?? 0} | ${(((statusCounts['FIXED-UNVERIFIED'] ?? 0) / totalFindings) * 100).toFixed(1)}% |
| VERIFIED | ${statusCounts['VERIFIED'] ?? 0} | ${(((statusCounts['VERIFIED'] ?? 0) / totalFindings) * 100).toFixed(1)}% |
| BLOCKED | ${statusCounts['BLOCKED'] ?? 0} | ${(((statusCounts['BLOCKED'] ?? 0) / totalFindings) * 100).toFixed(1)}% |
| WONT-FIX | ${statusCounts['WONT-FIX'] ?? 0} | ${(((statusCounts['WONT-FIX'] ?? 0) / totalFindings) * 100).toFixed(1)}% |
| **TOTAL** | **${totalFindings}** | **100.0%** |

### By Severity
| Severity | Total | Open / In Progress | Verified / Closed |
|---|---|---|---|
| P0 (Blocker) | ${severityCounts['P0']} | ${findings.filter((i) => i.severity === 'P0' && i.status !== 'VERIFIED' && i.status !== 'WONT-FIX').length} | ${findings.filter((i) => i.severity === 'P0' && (i.status === 'VERIFIED' || i.status === 'WONT-FIX')).length} |
| P1 (Critical) | ${severityCounts['P1']} | ${findings.filter((i) => i.severity === 'P1' && i.status !== 'VERIFIED' && i.status !== 'WONT-FIX').length} | ${findings.filter((i) => i.severity === 'P1' && (i.status === 'VERIFIED' || i.status === 'WONT-FIX')).length} |
| P2 (Moderate) | ${severityCounts['P2']} | ${findings.filter((i) => i.severity === 'P2' && i.status !== 'VERIFIED' && i.status !== 'WONT-FIX').length} | ${findings.filter((i) => i.severity === 'P2' && (i.status === 'VERIFIED' || i.status === 'WONT-FIX')).length} |
| P3 (Minor) | ${severityCounts['P3']} | ${findings.filter((i) => i.severity === 'P3' && i.status !== 'VERIFIED' && i.status !== 'WONT-FIX').length} | ${findings.filter((i) => i.severity === 'P3' && (i.status === 'VERIFIED' || i.status === 'WONT-FIX')).length} |

---

## 2. Blocked Work Items

| ID | Title | Tier | Severity | Blocking Reason & Unblocking Action |
|---|---|---|---|---|
`;

  const blocked = findings.filter((i) => i.status === 'BLOCKED');
  if (blocked.length === 0) {
    md += '| None | - | - | - | All items are eligible for processing |\n';
  } else {
    for (const b of blocked) {
      md += `| **${b.id}** | ${b.title} | ${b.tier} | ${b.severity} | ${b.notes.replace(/\n/g, ' ')} |\n`;
    }
  }

  md += `\n---\n\n## 3. Remediation Linear Work Queue (Topological Order)\n\n`;
  md += `| ID | Tier | Sev | Cluster | Status | Approval | Depends On | Title |\n`;
  md += `|---|---|---|---|---|---|---|---|\n`;

  for (const item of findings) {
    const deps = item.dependsOn?.length ? item.dependsOn.join(', ') : '-';
    md += `| **${item.id}** | ${item.tier} | ${item.severity} | ${item.cluster} | \`${item.status}\` | ${item.needsApproval} | ${deps} | ${item.title} |\n`;
  }

  return md;
}

export function validateTracker(updateMd = false) {
  if (!existsSync(TRACKER_JSON_PATH)) {
    console.error(`FAIL: Tracker JSON not found at ${TRACKER_JSON_PATH}`);
    process.exit(1);
  }

  let raw;
  try {
    raw = JSON.parse(readFileSync(TRACKER_JSON_PATH, 'utf8'));
  } catch (err) {
    console.error(`FAIL: Invalid JSON in ${TRACKER_JSON_PATH}: ${err.message}`);
    process.exit(1);
  }

  const items = Array.isArray(raw) ? raw : raw.items ?? raw.workItems;
  if (!Array.isArray(items)) {
    console.error('FAIL: tracker.json root must be an array or contain an `items` array.');
    process.exit(1);
  }

  const errors = [];
  const seenIds = new Set();
  const itemMap = new Map();

  for (let idx = 0; idx < items.length; idx++) {
    const item = items[idx];
    const prefix = `Item [${idx}] (${item.id || 'NO_ID'})`;

    if (!item.id || typeof item.id !== 'string') {
      errors.push(`${prefix}: Missing or non-string id`);
      continue;
    }

    if (seenIds.has(item.id)) {
      errors.push(`${prefix}: Duplicate ID detected: '${item.id}'`);
    }
    seenIds.add(item.id);
    itemMap.set(item.id, item);

    // Required fields check
    const requiredProps = [
      'title',
      'severity',
      'category',
      'tier',
      'cluster',
      'dependsOn',
      'blocks',
      'relatedFindings',
      'standardsRefs',
      'files',
      'effort',
      'owner',
      'status',
      'statusHistory',
      'reproCommand',
      'regressionTest',
      'fixCommit',
      'verifyEvidence',
      'siblingSweep',
      'needsApproval',
      'notes',
    ];

    for (const prop of requiredProps) {
      if (item[prop] === undefined) {
        errors.push(`${prefix}: Missing required field '${prop}'`);
      } else if (item[prop] === null && prop !== 'fixCommit') {
        errors.push(`${prefix}: Required field '${prop}' cannot be null`);
      }
    }

    // Enum checks
    if (!VALID_SEVERITIES.has(item.severity)) {
      errors.push(`${prefix}: Invalid severity '${item.severity}'. Expected P0..P3`);
    }
    if (!VALID_STATUSES.has(item.status)) {
      errors.push(`${prefix}: Invalid status '${item.status}'`);
    }
    if (!VALID_EFFORTS.has(item.effort)) {
      errors.push(`${prefix}: Invalid effort '${item.effort}'. Expected S, M, or L`);
    }
    if (!VALID_APPROVALS.has(item.needsApproval)) {
      errors.push(`${prefix}: Invalid needsApproval '${item.needsApproval}'`);
    }

    // Status state machine validation
    if (Array.isArray(item.statusHistory)) {
      if (item.statusHistory.length === 0) {
        errors.push(`${prefix}: statusHistory cannot be empty`);
      } else {
        const initialStatus = item.statusHistory[0].status;
        if (initialStatus !== 'OPEN') {
          errors.push(`${prefix}: Initial status must be 'OPEN', got '${initialStatus}'`);
        }

        for (let h = 0; h < item.statusHistory.length - 1; h++) {
          const from = item.statusHistory[h].status;
          const to = item.statusHistory[h + 1].status;
          const allowed = ALLOWED_TRANSITIONS[from];
          if (!allowed || !allowed.has(to)) {
            errors.push(`${prefix}: Illegal state transition in statusHistory: '${from}' -> '${to}'`);
          }
        }

        const lastRecorded = item.statusHistory[item.statusHistory.length - 1].status;
        if (lastRecorded !== item.status) {
          errors.push(`${prefix}: Current status '${item.status}' does not match last statusHistory entry '${lastRecorded}'`);
        }
      }
    } else {
      errors.push(`${prefix}: statusHistory must be an array`);
    }

    // WONT-FIX check for P0/P1
    if (item.status === 'WONT-FIX' && (item.severity === 'P0' || item.severity === 'P1')) {
      const hasApprovalNote =
        (item.notes && item.notes.toLowerCase().includes('owner-approved')) ||
        (Array.isArray(item.statusHistory) &&
          item.statusHistory.some((h) => h.note && h.note.toLowerCase().includes('owner-approved')));
      if (!hasApprovalNote) {
        errors.push(`${prefix}: P0/P1 cannot be WONT-FIX without an 'owner-approved' note in notes or statusHistory`);
      }
    }

    // VERIFIED checks
    if (item.status === 'VERIFIED') {
      if (!item.regressionTest || typeof item.regressionTest !== 'string') {
        errors.push(`${prefix}: VERIFIED item requires a valid regressionTest path`);
      }
      if (!item.fixCommit || typeof item.fixCommit !== 'string') {
        errors.push(`${prefix}: VERIFIED item requires fixCommit`);
      }
      if (!Array.isArray(item.verifyEvidence) || item.verifyEvidence.length < 2) {
        errors.push(`${prefix}: VERIFIED item requires verifyEvidence with before and after proof (>= 2 entries)`);
      }
      if (!item.siblingSweep || !item.siblingSweep.done || !item.siblingSweep.queryUsed) {
        errors.push(`${prefix}: VERIFIED item requires completed siblingSweep with queryUsed and done=true`);
      }

      // Verifier identity different from fixer session
      const fixerEntry = (item.statusHistory || []).find((h) => h.status === 'FIXED-UNVERIFIED');
      const verifierEntry = (item.statusHistory || []).find((h) => h.status === 'VERIFIED');
      if (fixerEntry && verifierEntry && fixerEntry.session && verifierEntry.session && fixerEntry.session === verifierEntry.session) {
        errors.push(`${prefix}: Verifier session '${verifierEntry.session}' must be distinct from fixer session '${fixerEntry.session}'`);
      }
    }
  }

  // Dependency graph checks
  for (const item of items) {
    if (item.status === 'IN-PROGRESS' || item.status === 'FIXED-UNVERIFIED' || item.status === 'VERIFIED') {
      const deps = item.dependsOn || [];
      for (const depId of deps) {
        const dep = itemMap.get(depId);
        if (!dep) {
          errors.push(`Item '${item.id}': depends on non-existent item '${depId}'`);
        } else if (dep.status !== 'VERIFIED' && dep.status !== 'WONT-FIX') {
          errors.push(`Item '${item.id}': has status '${item.status}' but dependsOn item '${depId}' is '${dep.status}' (must be VERIFIED)`);
        }
      }
    }
  }

  // Markdown synchronization check
  const generatedMd = generateMarkdown(items);
  if (updateMd || !existsSync(TRACKER_MD_PATH)) {
    writeFileSync(TRACKER_MD_PATH, generatedMd, 'utf8');
    console.log(`[check-tracker] Wrote synchronized tracker.md`);
  } else {
    const existingMd = readFileSync(TRACKER_MD_PATH, 'utf8');
    if (existingMd !== generatedMd) {
      errors.push(`tracker.md is out of date with tracker.json. Re-run check-tracker.mjs --generate-md to regenerate.`);
    }
  }

  if (errors.length > 0) {
    console.error(`\n❌ Tracker validation FAILED with ${errors.length} error(s):`);
    for (const err of errors) {
      console.error(`  - ${err}`);
    }
    process.exit(1);
  }

  console.log(`\n✅ Tracker validation PASSED: ${items.length} work items cleanly verified.`);
  return { ok: true, count: items.length };
}

// Direct execution
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const updateMd = process.argv.includes('--generate-md') || process.argv.includes('--update-md');
  validateTracker(updateMd);
}
